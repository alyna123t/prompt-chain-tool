// Minimal line-icon set — one size (16), one stroke (1.5), currentColor so each
// icon takes its text role's color. Replaces emoji used as icons.

type IconProps = { className?: string; size?: number };

function Base({
  className = "",
  size = 16,
  children,
}: IconProps & { children: React.ReactNode }) {
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={1.5}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      className={className}
    >
      {children}
    </svg>
  );
}

