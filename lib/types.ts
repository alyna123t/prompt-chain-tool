// Shapes of the Supabase tables this app owns (same database as the other apps —
// profiles / is_superadmin are shared; the prompt_chain_* tables are new here).

export type Profile = {
  id: string;
  email: string | null;
  first_name: string | null;
  last_name: string | null;
  avatar_url: string | null;
  is_superadmin: boolean;
  created_at: string;
};

export type PromptChain = {
  id: string;
  user_id: string | null;
  name: string;
  description: string | null;
  created_at: string;
  updated_at: string;
};

// One step in a chain. `position` is 1-based and contiguous within a chain;
// reordering renumbers the affected rows.
export type PromptChainStep = {
  id: string;
  chain_id: string;
  position: number;
  name: string;
  prompt: string;
  created_at: string;
  updated_at: string;
};

// The output of one step during a generation run.
export type StepResult = {
  name: string;
  prompt: string;
  output: string;
};

// A single run of a chain: the input that was fed in, every step's output, and
// the final result. This is the "media generated by a specific prompt chain".
export type GeneratedMedia = {
  id: string;
  chain_id: string;
  created_by: string | null;
  input_type: "text" | "image";
  input_text: string | null;
  input_image_url: string | null; // a data URL, when the image was small enough to store
  steps: StepResult[];
  final_output: string;
  used_mock: boolean;
  created_at: string;
};

export function fullName(p: Pick<Profile, "first_name" | "last_name">): string {
  return [p.first_name, p.last_name].filter(Boolean).join(" ").trim();
}
